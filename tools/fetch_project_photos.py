#!/usr/bin/env python3
"""Download, verify and optimise the project photography listed in photography/manifest.json.

Run from the repo root on your own machine (needs Python 3 and Pillow: pip install Pillow):

    python3 tools/fetch_project_photos.py
    (Windows: py tools/fetch_project_photos.py)

Downloads are throttled (--delay, default 3 s) and retried with back-off on HTTP 429.
If anything fails, js/photography.js is not written; re-run and only the missing images are fetched.

What it does, for every image in the manifest:
  1. Downloads the original from Wikimedia Commons into a cache folder OUTSIDE the repo
     (default ~/.cache/wh-photos), unless it is already there or in --source-dir.
  2. Checks the file's SHA-1 against the manifest, so only the verified photo is used.
  3. Writes WebP variants to assets/img/<file>-<width>.webp at 800 / 1600 / 2400 px
     (never wider than the original; nothing is upscaled).
  4. Writes js/photography.js (hand-off data for the site) and photography/optimised.csv
     (output sizes), so dimensions and credits stay in step with the files.

Originals never enter the repo. js/data.js is not touched.
"""
import argparse, csv, hashlib, io, json, os, sys, time, urllib.error, urllib.parse, urllib.request
from pathlib import Path

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")

ROOT = Path(__file__).resolve().parent.parent
WIDTHS = [800, 1600, 2400]
# Wikimedia asks automated clients for a descriptive User-Agent with a way to reach the operator.
UA = "WillisHazellDemoPhotoFetch/1.1 (https://github.com/TomJRushton/WHDemoSite; one-off fetch of manifest images) python-urllib"


def sha1(b):
    return hashlib.sha1(b).hexdigest()


def safe_url(url):
    """Percent-encode non-ASCII characters (e.g. an en dash in a file name) so urllib can send the request."""
    parts = urllib.parse.urlsplit(url)
    return urllib.parse.urlunsplit(parts._replace(path=urllib.parse.quote(parts.path, safe="/%:@!$&'()*+,;=-._~")))


def get_original(img, cache, source_dir, delay, retries):
    """Return the original's bytes from --source-dir or the cache, else download it politely.
    Waits `delay` seconds before every network request, and on HTTP 429/503 backs off
    (honouring Retry-After) and retries up to `retries` times."""
    name = img["commonsTitle"]
    for d in [source_dir, cache]:
        if d and (d / name).exists():
            return (d / name).read_bytes(), False
    req = urllib.request.Request(safe_url(img["originalUrl"]), headers={"User-Agent": UA})
    wait = delay
    for attempt in range(retries + 1):
        time.sleep(wait)
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                data = r.read()
            (cache / name).write_bytes(data)
            return data, True
        except urllib.error.HTTPError as e:
            if e.code not in (429, 503) or attempt == retries:
                raise
            ra = e.headers.get("Retry-After") if e.headers else None
            wait = max(int(ra) if ra and ra.isdigit() else 0, delay * 2 ** (attempt + 2))
            print(f"     HTTP {e.code}, waiting {wait}s before retry {attempt + 1}/{retries}", flush=True)


def photo_entry(img, widths, w, h):
    """One WH_PHOTOS record. licenceUrl, dateTaken and photographer are carried so the site can link the
    licence (a CC BY / CC BY-SA requirement) and date construction-stage photos."""
    return {
        "name": img["file"], "maxW": widths[-1], "widths": widths, "w": w, "h": h,
        "role": img["role"], "phase": img["phase"], "alt": img["alt"],
        "credit": img["attribution"], "source": img["sourcePage"], "licence": img["licence"],
        "licenceUrl": img["licenceUrl"], "dateTaken": img.get("dateTaken"), "photographer": img["photographer"],
    }


def write_js(path, photos):
    js = ("/* Generated by tools/fetch_project_photos.py from photography/manifest.json. Do not edit by hand.\n"
          "   Licensed project photography (Wikimedia Commons); credits must stay visible where shown. */\n"
          "window.WH_PHOTOS = " + json.dumps(photos, indent=1, ensure_ascii=False) + ";\n")
    Path(path).write_text(js, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=str(ROOT / "photography/manifest.json"))
    ap.add_argument("--cache", default=str(Path.home() / ".cache/wh-photos"))
    ap.add_argument("--source-dir", help="folder of originals you downloaded by hand (named as commonsTitle)")
    ap.add_argument("--out-img", default=str(ROOT / "assets/img"))
    ap.add_argument("--out-js", default=str(ROOT / "js/photography.js"))
    ap.add_argument("--quality", type=int, default=82)
    ap.add_argument("--delay", type=float, default=3.0, help="seconds to wait before each download (default 3)")
    ap.add_argument("--retries", type=int, default=4, help="retries per image after HTTP 429/503 (default 4)")
    ap.add_argument("--from-assets", action="store_true",
                    help="no downloads: rebuild js/photography.js from the manifest and the WebP files already in "
                         "assets/img (use after a full run, e.g. when the manifest metadata changes)")
    ap.add_argument("--allow-partial", action="store_true",
                    help="write js/photography.js even if some images failed (default: only when all succeed)")
    a = ap.parse_args()

    man = json.load(open(a.manifest, encoding="utf-8"))
    cache = Path(a.cache); cache.mkdir(parents=True, exist_ok=True)
    src = Path(a.source_dir) if a.source_dir else None
    out = Path(a.out_img); out.mkdir(parents=True, exist_ok=True)

    photos, rows, failed = {}, [], []
    if a.from_assets:
        for p in man["projects"]:
            for img in p["images"]:
                files = sorted(out.glob(f'{img["file"]}-*.webp'), key=lambda f: int(f.stem.rsplit("-", 1)[1]))
                widths = [int(f.stem.rsplit("-", 1)[1]) for f in files]
                if not widths:
                    failed.append(f'{p["id"]} / {img["file"]}: no WebP files in {out}'); continue
                w, h = Image.open(files[-1]).size
                photos.setdefault(p["id"], []).append(photo_entry(img, widths, w, h))
                print("ok  ", p["id"], "/", img["file"], widths)
        if failed:
            print("\nNOT PROCESSED:"); [print("  " + f) for f in failed]; sys.exit(1)
        write_js(a.out_js, photos)
        print(f"\njs/photography.js rebuilt from existing WebP files for {sum(len(v) for v in photos.values())} photos.")
        return

    for p in man["projects"]:
        for img in p["images"]:
            label = f'{p["id"]} / {img["file"]}'
            try:
                data, fetched = get_original(img, cache, src, a.delay, a.retries)
            except Exception as e:
                failed.append(f"{label}: download failed ({e})"); continue
            if sha1(data) != img["sha1"]:
                failed.append(f"{label}: SHA-1 mismatch, file skipped"); continue
            im = ImageOps.exif_transpose(Image.open(io.BytesIO(data))).convert("RGB")
            W, H = im.size
            widths = [w for w in WIDTHS if w < W] + [min(W, WIDTHS[-1])]
            widths = sorted(set(widths))
            for w in widths:
                h = round(H * w / W)
                f = out / f'{img["file"]}-{w}.webp'
                im.resize((w, h), Image.LANCZOS).save(f, "WEBP", quality=a.quality, method=6)
                rows.append([p["id"], img["file"], img["commonsTitle"], f"{W}x{H}", f"{w}x{h}", f.stat().st_size])
            photos.setdefault(p["id"], []).append(photo_entry(img, widths, widths[-1], round(H * widths[-1] / W)))
            print("ok  ", label, f"{W}x{H} ->", widths)

    if failed and not a.allow_partial:
        print("\nNOT PROCESSED:"); [print("  " + f) for f in failed]
        print(f"\n{len(failed)} image(s) failed, so js/photography.js and photography/optimised.csv were NOT written.\n"
              "Downloaded originals are cached, so re-running the script only fetches what is missing.")
        sys.exit(1)

    write_js(a.out_js, photos)
    with open(ROOT / "photography/optimised.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh); w.writerow(["project", "file", "commonsTitle", "original", "output", "bytes"]); w.writerows(rows)

    total = sum(r[5] for r in rows)
    print(f"\n{len(rows)} WebP files, {total/1024:.0f} KB total, for {sum(len(v) for v in photos.values())} photos.")
    if failed:
        print("\nNOT PROCESSED:"); [print("  " + f) for f in failed]; sys.exit(1)


if __name__ == "__main__":
    main()
